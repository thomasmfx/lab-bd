CREATE OR REPLACE NONEDITIONABLE TRIGGER "TG_HIST_COMPRAS" 
AFTER INSERT OR UPDATE OR DELETE ON "COMPRAS"
FOR EACH ROW
DECLARE
    v_agora    TIMESTAMP := SYSTIMESTAMP;
    v_operacao CHAR(1);
BEGIN
    IF NOT INSERTING THEN
        UPDATE "COMPRAS_HIST"
           SET "COM_HIST_DT_FIM" = v_agora
         WHERE "COM_ID" = :OLD.COM_ID
           AND "COM_HIST_DT_FIM" IS NULL;
    END IF;

    IF NOT DELETING THEN
        v_operacao := CASE WHEN INSERTING THEN 'I' ELSE 'U' END;
        INSERT INTO "COMPRAS_HIST" (
            "COM_HIST_ID",
            "COM_ID",
            "COM_DT_PEDIDO",
            "COM_OS",
            "COM_DESENHO",
            "COM_MATERIAL",
            "COM_DESCRICAO_MATERIAL",
            "COM_QTD",
            "COM_PERFIL",
            "COM_DIAMETRO_INT",
            "COM_DIAMETRO_EXT",
            "COM_ESPESSURA",
            "COM_LARGURA",
            "COM_COMPRIMENTO",
            "COM_DT_PRAZO",
            "COM_STATUS",
            "COM_FORNECEDOR",
            "COM_DT_COMPRA_MATERIAL",
            "COM_FRETE",
            "COM_NFE",
            "COM_DT_CHEGADA_MATERIAL",
            "COM_INFO_ADICIONAIS",
            "COM_HIST_DT_INICIO",
            "COM_HIST_OPERACAO",
            "COM_HIST_USUARIO"
        ) VALUES (
            "SEQ_COMPRAS_HIST".NEXTVAL,
            :NEW.COM_ID,
            :NEW.COM_DT_PEDIDO,
            :NEW.COM_OS,
            :NEW.COM_DESENHO,
            :NEW.COM_MATERIAL,
            :NEW.COM_DESCRICAO_MATERIAL,
            :NEW.COM_QTD,
            :NEW.COM_PERFIL,
            :NEW.COM_DIAMETRO_INT,
            :NEW.COM_DIAMETRO_EXT,
            :NEW.COM_ESPESSURA,
            :NEW.COM_LARGURA,
            :NEW.COM_COMPRIMENTO,
            :NEW.COM_DT_PRAZO,
            :NEW.COM_STATUS,
            :NEW.COM_FORNECEDOR,
            :NEW.COM_DT_COMPRA_MATERIAL,
            :NEW.COM_FRETE,
            :NEW.COM_NFE,
            :NEW.COM_DT_CHEGADA_MATERIAL,
            :NEW.COM_INFO_ADICIONAIS,
            v_agora,
            v_operacao,
            USER
        );
    END IF;
END;
/
ALTER TRIGGER "TG_HIST_COMPRAS" ENABLE;

