--  Banco temporal: histórico de versões de cada tabela
--  Executar depois de controle_compras_ddl.sql.
--
--  Cada tabela <T> ganha <T>_HIST, alimentada pelo trigger TG_HIST_<T>.
--  Uma versão vale no intervalo [DT_INICIO, DT_FIM); DT_FIM nulo = versão vigente.
--  OPERACAO: I = versão criada por INSERT, U = por UPDATE.
--  DELETE só fecha a versão: linha apagada = versão com DT_FIM e sem versão posterior.
--
--  Estado de uma tabela no instante :t, por exemplo:
--    SELECT * FROM COMPRAS_HIST
--     WHERE COM_HIST_DT_INICIO <= :t
--       AND (COM_HIST_DT_FIM > :t OR COM_HIST_DT_FIM IS NULL);
--------------------------------------------------------

